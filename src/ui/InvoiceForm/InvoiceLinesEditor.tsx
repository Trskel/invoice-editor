import { Button, Col, Flex, InputNumber, Row } from 'antd'
import {
  Controller,
  useFieldArray,
  useFormState,
  useWatch,
} from 'react-hook-form'
import formatAmount from '../../helpers/formatAmount'
import formatRate from '../../helpers/formatRate'
import { pricedLines } from '../../model/invoiceForm'
import ProductAutoComplete from '../ProductAutoComplete/ProductAutoComplete'
import FieldError from './FieldError'
import { InvoiceControl } from './types'

// Column widths shared by the header and the rows (antd's grid has 24 columns).
const COLUMNS = {
  product: 6,
  quantity: 4,
  unit: 3,
  price: 4,
  rate: 3,
  amount: 4,
}

type LineRowProps = {
  control: InvoiceControl
  // Position in the list, from 0. Names use the displayed number, from 1.
  index: number
  onRemove: () => void
}

const LineRow = ({ control, index, onRemove }: LineRowProps) => {
  const line = useWatch({ control, name: `lines.${index}` })
  const { errors } = useFormState({ control, name: `lines.${index}` })
  const lineNumber = index + 1
  const productError = errors.lines?.[index]?.product?.message
  const quantityError = errors.lines?.[index]?.quantity?.message
  const productErrorId = `line-${lineNumber}-product-error`
  const quantityErrorId = `line-${lineNumber}-quantity-error`
  // The amount of a complete line, undefined otherwise.
  const amount = pricedLines([line])[0]?.price

  return (
    <Row data-line={lineNumber} gutter={12} align="top">
      <Col span={COLUMNS.product}>
        <Flex vertical gap="small">
          <Controller
            control={control}
            name={`lines.${index}.product`}
            render={({ field, fieldState }) => (
              <ProductAutoComplete
                aria-label={`Product, line ${lineNumber}`}
                aria-invalid={fieldState.invalid}
                aria-describedby={productError ? productErrorId : undefined}
                status={productError ? 'error' : undefined}
                value={field.value}
                onChange={field.onChange}
                ref={field.ref}
              />
            )}
          />
          <FieldError id={productErrorId} message={productError} />
        </Flex>
      </Col>
      <Col span={COLUMNS.quantity}>
        <Flex vertical gap="small">
          <Controller
            control={control}
            name={`lines.${index}.quantity`}
            render={({ field, fieldState }) => (
              // No `min`, `max` or `precision`: antd would correct the value
              // on blur and hide the error the user must see.
              <InputNumber
                aria-label={`Quantity, line ${lineNumber}`}
                aria-invalid={fieldState.invalid}
                aria-describedby={quantityError ? quantityErrorId : undefined}
                status={quantityError ? 'error' : undefined}
                value={field.value}
                onChange={field.onChange}
                ref={field.ref}
              />
            )}
          />
          <FieldError id={quantityErrorId} message={quantityError} />
        </Flex>
      </Col>
      <Col span={COLUMNS.unit}>{line.product?.unit ?? '-'}</Col>
      <Col span={COLUMNS.price}>
        {line.product ? formatAmount(line.product.unit_price) : '-'}
      </Col>
      <Col span={COLUMNS.rate}>
        {line.product ? formatRate(line.product.vat_rate) : '-'}
      </Col>
      <Col span={COLUMNS.amount}>
        <Flex justify="space-between" align="start" gap="small">
          <span data-testid="line-amount">
            {amount === undefined ? '-' : formatAmount(amount)}
          </span>
          <Button
            type="link"
            danger
            aria-label={`Remove line ${lineNumber}`}
            onClick={onRemove}
          >
            Remove
          </Button>
        </Flex>
      </Col>
    </Row>
  )
}

const InvoiceLinesEditor = ({ control }: { control: InvoiceControl }) => {
  // `fields[i].id` is a key generated by the library, not the line's own id:
  // it keeps a row's state with its row when another row is removed.
  const { fields, append, remove } = useFieldArray({ control, name: 'lines' })
  const { errors } = useFormState({ control, name: 'lines' })
  const listError = errors.lines?.root?.message ?? errors.lines?.message

  return (
    <Flex vertical gap="small">
      {/* The columns are a fixed grid: on a narrow viewport let them scroll
          inside this container instead of widening the page. */}
      <div style={{ overflowX: 'auto' }}>
        <div style={{ minWidth: 720 }}>
          <Row gutter={12}>
            <Col span={COLUMNS.product}>Product</Col>
            <Col span={COLUMNS.quantity}>Quantity</Col>
            <Col span={COLUMNS.unit}>Unit</Col>
            <Col span={COLUMNS.price}>Unit price</Col>
            <Col span={COLUMNS.rate}>VAT rate</Col>
            <Col span={COLUMNS.amount}>Amount</Col>
          </Row>

          {fields.map((field, index) => (
            <LineRow
              key={field.id}
              control={control}
              index={index}
              onRemove={() => remove(index)}
            />
          ))}
        </div>
      </div>

      <FieldError id="lines-error" message={listError} />

      <div>
        <Button onClick={() => append({ product: null, quantity: null })}>
          Add line
        </Button>
      </div>
    </Flex>
  )
}

export default InvoiceLinesEditor
